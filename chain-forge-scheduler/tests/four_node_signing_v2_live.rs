//! Four REAL node processes on a fresh `qattice-v2` genesis, driven by real signers (TEST-ONLY, feature `signing-v2`; disposable keys).
//!
//! | ID   | Check (v2 chain, `tests/devnet/qattice-v2/genesis-4node-qattice-v2.json`) |
//! |------|----------------------------------------------------------------------------|
//! | V-01 | a transfer signed locally by `qcb-wallet transfer-v2` (first use) commits; all 4 nodes include it in the same block and agree on the state root |
//! | V-02 | a second transfer from the now-bound key (no key carried) commits |
//! | V-03 | an exact replay of an executed signed tx changes nothing on any node |
//! | V-04 | the same signature moved to a new nonce / id (H0-4 replay) is refused: `GET /api/tx/{id}` reports `rejected` with code `signing_v2_authorization` |
//! | V-05 | a body edited after signing is refused: same code |
//! | V-06 | a v2 signature made for ANOTHER chain id is refused: same code |
//! | V-07 | a LEGACY-digest ML-DSA signature is refused on the v2 chain (no cross-acceptance) |
//! | V-08 | prepare -> `qcb-claim-signer` -> submit settles a `ClaimResearchReward` on the real nodes: block inclusion, treasury debited, recipient credited, roots agree |
//! | V-09 | the settled claim cannot be replayed (directly at a node, or through the scheduler) and a wrong `--expect-chain-id` makes the signer refuse |
//! | L-01 | LEGACY chain (the unchanged `genesis-4node-mldsa.json`, no profile) with the same binary: a legacy-signed transfer commits; roots agree |
//! | L-02 | a v2-signed transaction is refused on the legacy chain (no cross-acceptance the other way) |
//!
//! Keys: validators use the PUBLIC test keys in `tests/devnet/keys/mldsa/`; every user/operator key is generated by the test in a
//! temp dir and deleted afterwards. No production key is used. Nodes are started first-node-first (the node dials `--bootstrap` once
//! and does not retry), so this test does not depend on the P2P bootstrap fix.
//!
//! ## Run (build the binaries first; this test starts them)
//! ```
//! cargo build -p chain-forge-node   --features signing-v2
//! cargo build -p chain-forge-wallet --features signing-v2 --bin qcb-wallet
//! cargo test  -p chain-forge-scheduler --features signing-v2 --test four_node_signing_v2_live -- --nocapture --test-threads=1
//! ```
//! Per CLAUDE.md: marked done only after it passes on Windows (MINGW64).
