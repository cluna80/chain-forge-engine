// ── paths ────────────────────────────────────────────────────────────────────────────────────────────────────────────────
fn repo_root() -> PathBuf { PathBuf::from(env!("CARGO_MANIFEST_DIR")).parent().unwrap().to_path_buf() }
fn target_dir() -> PathBuf { std::env::var("CARGO_TARGET_DIR").map(PathBuf::from).unwrap_or_else(|_| repo_root().join("target")) }
fn built_binary(name: &str, build_hint: &str) -> PathBuf {
    let exe = format!("{name}{}", std::env::consts::EXE_SUFFIX);
    let mut found: Vec<(std::time::SystemTime, PathBuf)> = ["debug", "release"].iter()
        .filter_map(|p| { let f = target_dir().join(p).join(&exe); f.metadata().and_then(|m| m.modified()).ok().map(|t| (t, f)) }).collect();
    found.sort();
    found.pop().map(|x| x.1).unwrap_or_else(|| panic!("{name} is not built; run: {build_hint}"))
}
fn node_bin() -> PathBuf { built_binary("chain-forge-node", "cargo build -p chain-forge-node --features signing-v2") }
fn wallet_bin() -> PathBuf { built_binary("qcb-wallet", "cargo build -p chain-forge-wallet --features signing-v2 --bin qcb-wallet") }
fn hex(b: &[u8]) -> String { b.iter().map(|x| format!("{x:02x}")).collect() }
fn free_port() -> u16 { TcpListener::bind("127.0.0.1:0").unwrap().local_addr().unwrap().port() }

// ── tiny blocking HTTP client for the nodes ───────────────────────────────────────────────────────────────────────────────
fn http_raw(method: &str, port: u16, path: &str, body: Option<&str>) -> Option<(u16, String)> {
    let mut s = TcpStream::connect_timeout(&format!("127.0.0.1:{port}").parse().unwrap(), Duration::from_millis(500)).ok()?;
    s.set_read_timeout(Some(Duration::from_millis(15_000))).ok()?;
    let req = match body {
        Some(b) => format!("{method} {path} HTTP/1.0\r\nHost: 127.0.0.1\r\nContent-Type: application/json\r\nContent-Length: {}\r\nConnection: close\r\n\r\n{b}", b.len()),
        None => format!("{method} {path} HTTP/1.0\r\nHost: 127.0.0.1\r\nConnection: close\r\n\r\n"),
    };
    s.write_all(req.as_bytes()).ok()?;
    let mut buf = String::new();
    s.read_to_string(&mut buf).ok()?;
    let status = buf.lines().next().and_then(|l| l.split_whitespace().nth(1)).and_then(|x| x.parse().ok()).unwrap_or(0);
    Some((status, buf.split("\r\n\r\n").nth(1).unwrap_or("").to_string()))
}
fn api_get(port: u16, path: &str) -> Option<Value> { http_raw("GET", port, path, None).and_then(|(_, b)| serde_json::from_str(&b).ok()) }
fn api_post(port: u16, path: &str, body: &str) -> (u16, Value) {
    match http_raw("POST", port, path, Some(body)) { Some((s, r)) => (s, serde_json::from_str(&r).unwrap_or(Value::Null)), None => (0, Value::Null) }
}
fn status(port: u16) -> Value { api_get(port, "/api/status").unwrap_or(Value::Null) }
fn height(port: u16) -> u64 { status(port)["height"].as_u64().unwrap_or(0) }
fn state_root(port: u16) -> String { status(port)["state_root"].as_str().unwrap_or("").to_string() }
fn balance(port: u16, addr: &str) -> u128 {
    api_get(port, &format!("/api/accounts/{addr}")).map(|v| {
        let b = &v["balances"]["uqcb"];
        b.as_u64().map(|n| n as u128).or_else(|| b.as_str().and_then(|s| s.parse().ok())).unwrap_or(0)
    }).unwrap_or(0)
}
fn nonce(port: u16, addr: &str) -> u64 { api_get(port, &format!("/api/accounts/{addr}")).and_then(|v| v["nonce"].as_u64()).unwrap_or(0) }
fn wait_tx_result(port: u16, id: &str, secs: u64) -> Option<Value> {
    let end = Instant::now() + Duration::from_secs(secs);
    while Instant::now() < end {
        if let Some(v) = api_get(port, &format!("/api/tx/{id}")) {
            let nf = v["error"].as_str().map_or(false, |e| e.contains("not found"));
            if !nf && (v.get("success").is_some() || v.get("error").is_some()) { return Some(v); }
        }
        std::thread::sleep(Duration::from_millis(300));
    }
    None
}

/// Poll `GET /api/tx/{id}` until the node reports the transaction as refused at admission (PR #116 contract), or give up.
fn wait_refusal(port: u16, id: &str, secs: u64) -> Option<Value> {
    let end = Instant::now() + Duration::from_secs(secs);
    while Instant::now() < end {
        if let Some(v) = api_get(port, &format!("/api/tx/{id}")) {
            if v["state"] == "rejected" { return Some(v); }
        }
        std::thread::sleep(Duration::from_millis(300));
    }
    None
}

// ── the network ──────────────────────────────────────────────────────────────────────────────────────────────────────────
struct Net { api: [u16; 4], nodes: Vec<Child>, dir: PathBuf }
impl Drop for Net { fn drop(&mut self) { for n in &mut self.nodes { let _ = n.kill(); let _ = n.wait(); } } }
impl Net {
    fn alice(&self) -> u16 { self.api[0] }
    fn dump_logs(&self) {
        for n in ["alice", "bob", "carol", "dave"] {
            if let Ok(t) = std::fs::read_to_string(self.dir.join("logs").join(format!("{n}.log"))) {
                let tail: Vec<&str> = t.lines().rev().take(12).collect();
                eprintln!("--- {n}.log (last lines)\n{}", tail.into_iter().rev().collect::<Vec<_>>().join("\n"));
            }
        }
    }
    /// Every node at the same height (>= h) with the same non-empty state root.
    fn assert_converged(&self, h: u64, what: &str) {
        let end = Instant::now() + Duration::from_secs(45);
        loop {
            let roots: Vec<String> = self.api.iter().map(|&p| state_root(p)).collect();
            let hs: Vec<u64> = self.api.iter().map(|&p| height(p)).collect();
            if hs.iter().all(|&x| x == hs[0] && x >= h) && roots.iter().all(|r| !r.is_empty() && *r == roots[0]) { return; }
            if Instant::now() > end { self.dump_logs(); panic!("{what}: nodes disagree: {roots:?} at {hs:?}"); }
            std::thread::sleep(Duration::from_millis(250));
        }
    }
    fn on_all<T: PartialEq + std::fmt::Debug>(&self, f: impl Fn(u16) -> T, what: &str) -> T {
        let v: Vec<T> = self.api.iter().map(|&p| f(p)).collect();
        for x in &v { assert_eq!(x, &v[0], "{what}: nodes differ: {v:?}"); }
        v.into_iter().next().unwrap()
    }
}

/// Render `template` plus extra accounts into a temp file.
fn render_genesis(template: &Path, dir: &Path, accounts: Vec<Value>, operator: Option<&str>) -> PathBuf {
    let mut g: Value = serde_json::from_str(&std::fs::read_to_string(template).unwrap()).unwrap();
    g["genesis_accounts"].as_array_mut().unwrap().extend(accounts);
    if let Some(op) = operator { g["settlement_operators"] = json!([op]); }
    let out = dir.join("genesis.json");
    std::fs::write(&out, serde_json::to_string_pretty(&g).unwrap()).unwrap();
    out
}

/// Start the four validators first-node-first, wait until they are connected and producing blocks.
fn start_net(genesis: &Path, tag: &str) -> Net {
    let dir = std::env::temp_dir().join(format!("qattice-v2-live-{tag}-{}", std::process::id()));
    let _ = std::fs::remove_dir_all(&dir);
    std::fs::create_dir_all(dir.join("logs")).unwrap();
    let api = [free_port(), free_port(), free_port(), free_port()];
    let p2p = [free_port(), free_port(), free_port(), free_port()];
    let names = ["alice", "bob", "carol", "dave"];
    let mut net = Net { api, nodes: vec![], dir: dir.clone() };
    for i in 0..4 {
        let data = dir.join("data").join(names[i]);
        std::fs::create_dir_all(&data).unwrap();
        let log = std::fs::File::create(dir.join("logs").join(format!("{}.log", names[i]))).unwrap();
        let mut cmd = Command::new(node_bin());
        cmd.arg("--genesis").arg(genesis).arg("--validator").arg(format!("qcb1{}", names[i]))
            .arg("--api-port").arg(api[i].to_string()).arg("--p2p-port").arg(p2p[i].to_string()).arg("--data-dir").arg(&data)
            .arg("--key-file").arg(repo_root().join("tests/devnet/keys/mldsa").join(format!("{}.key.json", names[i])));
        if i > 0 { cmd.arg("--bootstrap").arg(format!("/ip4/127.0.0.1/tcp/{}", p2p[0])); }
        cmd.stdout(log.try_clone().unwrap()).stderr(log).stdin(Stdio::null());
        net.nodes.push(cmd.spawn().unwrap_or_else(|e| panic!("spawn {}: {e}", names[i])));
        let end = Instant::now() + Duration::from_secs(40);
        while status(api[i]).is_null() {
            if Instant::now() > end { net.dump_logs(); panic!("{} did not come up", names[i]); }
            std::thread::sleep(Duration::from_millis(200));
        }
        std::thread::sleep(Duration::from_secs(1));
    }
    let end = Instant::now() + Duration::from_secs(60);
    loop {
        let peers: Vec<u64> = api.iter().map(|&p| status(p)["peer_count"].as_u64().unwrap_or(0)).collect();
        let hs: Vec<u64> = api.iter().map(|&p| height(p)).collect();
        if peers.iter().all(|&p| p > 0) && hs.iter().all(|&h| h >= 2) { break; }
        if Instant::now() > end { net.dump_logs(); panic!("the four nodes did not connect and produce blocks: peers {peers:?} heights {hs:?}"); }
        std::thread::sleep(Duration::from_millis(500));
    }
    net
}

// ── wallets and signers ──────────────────────────────────────────────────────────────────────────────────────────────────
struct W { file: String, address: String, public_key: String }
fn new_wallet(dir: &Path, label: &str) -> W {
    let file = dir.join(format!("{label}.wallet.json")).to_string_lossy().to_string();
    let kf = chain_forge_wallet::generate_wallet(&file, label, PASS).expect("generate wallet");
    let out = Command::new(wallet_bin()).args(["address", "--wallet", &file]).output().unwrap();
    let cli_addr = String::from_utf8_lossy(&out.stdout).trim().to_string();
    assert!(cli_addr.contains(&kf.address), "the CLI must derive the wallet's address: cli={cli_addr:?} lib={}", kf.address);
    W { file, address: kf.address, public_key: kf.public_key }
}
/// `qcb-wallet transfer-v2` without `--node`: prints the signed transaction JSON (the wallet signs locally; nothing is sent).
fn sign_transfer(w: &W, to: &str, amount: u64, nonce: u64, chain: &str, id: &str, first_use: bool) -> Value {
    let mut c = Command::new(wallet_bin());
    c.args(["transfer-v2", "--wallet", &w.file, "--to", to, "--amount", &amount.to_string(), "--nonce", &nonce.to_string(), "--chain-id", chain, "--id", id])
        .env("QCB_WALLET_PASSPHRASE", PASS);
    if first_use { c.arg("--first-use"); }
    let o = c.output().unwrap();
    assert!(o.status.success(), "transfer-v2 failed: {}", String::from_utf8_lossy(&o.stderr));
    serde_json::from_slice(&o.stdout).unwrap_or_else(|e| panic!("transfer-v2 printed no JSON ({e}): {}", String::from_utf8_lossy(&o.stdout)))
}
fn legacy_key() -> (chain_forge_crypto::KeyPair, String) {
    let kp = MlDsaScheme.generate_keypair("four-node-signing-v2-legacy-key").expect("keygen");
    let addr = Address::from_public_key_schemed(&kp.public_key, "qcb", HashWidth::Bits256, AddressScheme::PostQuantum).as_str().to_string();
    (kp, addr)
}
/// A transfer signed with the LEGACY ML-DSA digest (the pre-v2 rule), carrying its key as on first use.
fn legacy_transfer(kp: &chain_forge_crypto::KeyPair, sender: &str, to: &str, id: &str, nonce: u64, chain: &str) -> Value {
    let mut tx = Transaction::transfer(id, sender, to, "uqcb", 1_000, nonce);
    tx.gas_limit = 200_000;
    let body = serde_json::to_string(&tx.body).unwrap();
    let sig = MlDsaScheme.sign(&mldsa_tx_prehash(chain, body.as_bytes()), kp).expect("legacy sign");
    tx.pq_signatures = vec![format!("mldsa65:{}", hex(&sig.bytes))];
    tx.sig_scheme = Some(SchemeId::MlDsa);
    tx.pq_public_key = kp.public_key.clone();
    serde_json::to_value(&tx).unwrap()
}

fn account(label: &str, address: &str, balance: &str, role: &str) -> Value { json!({ "label": label, "address": address, "balance": balance, "role": role }) }

/// Submit; it must be refused or, if admitted, must fail at execution, and `who`'s (nonce, balance) must not move on any node.
fn expect_not_applied(net: &Net, tx: &Value, who: &str, what: &str, expect_code: Option<&str>) {
    let snap = || net.api.iter().map(|&p| (nonce(p, who), balance(p, who))).collect::<Vec<_>>();
    let before = snap();
    let id = tx["id"].as_str().unwrap().to_string();
    let (code, resp) = api_post(net.alice(), "/api/tx", &tx.to_string());
    if code == 400 {
        println!("    {what}: refused at the API (400): {}", resp["message"].as_str().unwrap_or(&resp.to_string()).chars().take(110).collect::<String>());
    } else {
        assert_eq!(resp["status"], "queued", "{what}: unexpected answer {code} {resp}");
        // Admitted by the API (stateless). The node's admission then decides, with account state. PR #116 contract: a refusal is reported by
        // GET /api/tx/{id} as state "rejected" with a stable code. Without an expected code, a recorded execution failure or no result at
        // all are also acceptable; a recorded SUCCESS never is.
        let refusal = wait_refusal(net.alice(), &id, 20);
        match (expect_code, refusal) {
            (Some(want), Some(r)) => {
                assert_eq!(r["code"], want, "{what}: wrong refusal code: {r}");
                assert_eq!((r["status"].as_str(), r["tx_id"].as_str()), (Some("rejected"), Some(id.as_str())), "{what}: {r}");
                assert!(r["message"].as_str().map_or(false, |m| !m.is_empty()) && r.get("success").is_none(), "{what}: {r}");
                println!("    {what}: admitted at the API, then refused by the node: GET /api/tx/{id} -> rejected, code {want}");
            }
            (Some(want), None) => { net.dump_logs(); panic!("{what}: expected GET /api/tx/{id} to report a rejection with code {want}, but none was reported"); }
            (None, Some(r)) => println!("    {what}: admitted at the API, then refused by the node with code {}", r["code"]),
            (None, None) => match wait_tx_result(net.alice(), &id, 30) {
                Some(r) => {
                    assert!(!r["success"].as_bool().unwrap_or(false), "{what}: {id} was EXECUTED SUCCESSFULLY: {r}");
                    println!("    {what}: admitted, then failed at execution");
                    net.assert_converged(r["height"].as_u64().unwrap_or(0), what);
                }
                None => println!("    {what}: admitted at the API, never executed (no result recorded)"),
            },
        }
        for &p in &net.api {
            let v = api_get(p, &format!("/api/tx/{id}")).unwrap_or(Value::Null);
            assert!(!v["success"].as_bool().unwrap_or(false), "{what}: {id} shows a successful result on :{p}: {v}");
        }
    }
    std::thread::sleep(Duration::from_secs(5));
    net.assert_converged(0, what);
    assert_eq!(before, snap(), "{what}: the (nonce, balance) of {who} changed on some node");
}
/// Submit a tx that must commit, on all four nodes, in the same block, with matching roots.
fn expect_committed(net: &Net, tx: &Value, what: &str) -> u64 {
    let id = tx["id"].as_str().unwrap();
    let (code, resp) = api_post(net.alice(), "/api/tx", &tx.to_string());
    assert!(code == 200 || code == 202, "{what}: node answered {code} {resp}");
    assert_eq!(resp["status"], "queued", "{what}: {resp}");
    let r = wait_tx_result(net.alice(), id, 90).unwrap_or_else(|| { net.dump_logs(); panic!("{what}: no result for {id}") });
    assert!(r["success"].as_bool().unwrap_or(false), "{what}: {id} must succeed: {r}");
    let h = r["height"].as_u64().expect("height");
    net.assert_converged(h, what);
    for &p in &net.api {
        let b = api_get(p, &format!("/api/blocks/{h}")).unwrap_or(Value::Null);
        assert!(b["tx_ids"].as_array().map_or(false, |a| a.iter().any(|x| x == id)), "{what}: block {h} on :{p} does not list {id}: {b}");
    }
    let hash = net.on_all(|p| api_get(p, &format!("/api/blocks/{h}")).map(|b| b["block_hash"].clone()).unwrap_or(Value::Null), what);
    assert!(hash.is_string(), "{what}: no block hash");
    println!("    {what}: {id} committed in block {h} ({}) on all 4 nodes, roots agree", hash.as_str().unwrap().chars().take(12).collect::<String>());
    h
}

// ── an accepted research task for the scheduler (public data only) ───────────────────────────────────────────────────────
async fn accepted_task() -> (Arc<dyn ResearchDb>, String, String) {
    let db = MemResearchDb::new();
    let obj = NewObjective {
        objective_id: "ch::obj::s".into(), challenge_id: "ch".into(), slug: "s".into(), track: "hash".into(), algorithm_version: "sha256_v1".into(),
        range_start: 0, range_end: 1_000, workload_class: "cpu".into(), verification_spec: json!({ "method": "sha256_preimage" }), verification_quorum: 2,
    };
    let obj_id = obj.objective_id.clone();
    let task = NewTask {
        task_id: format!("{obj_id}::task::0"), objective_id: obj_id.clone(), range_start: 0, range_end: 1_000, workload_class: "cpu".into(), input_seed: 1,
        phase: 1, parent_hash: None, phase1_miner_id: None, task_kind: "pocd_phase1".into(), avl_seed_index: None, avl_bit_index: None,
    };
    db.insert_objective(obj).await.unwrap();
    db.upsert_tasks(vec![task]).await.unwrap();
    let sched = ResearchScheduler::new(Arc::new(db.clone())).with_lease_secs(60);
    let row = sched.assign_task(&obj_id, "cpu", "miner_a").await.unwrap();
    let gen = row.lease_generation;
    sched.submit_result(&row.task_id, "miner_a", gen, NewExperimentResult {
        task_id: row.task_id.clone(), receipt_id: format!("rcpt_a_{gen}"), miner_id: "miner_a".into(), content_hash: format!("hash_miner_a_{gen}"),
        result_payload: json!({ "nonce": gen, "winning_hash": "aa".repeat(32), "phase": 1 }), algorithm_version: "sha256_v1".into(), workload_version: "1.0".into(),
        seal_nonce: Some(gen as u64), avl_original_hash: None, avl_flipped_hash: None, avl_xor_diff: None, avl_hamming_dist: None,
    }).await.unwrap();
    let r = db.list_results_for_task(&row.task_id).await.unwrap().remove(0);
    let engine = VerificationEngine::new(Arc::new(db.clone()));
    for (v, rc) in [("verifier_x", None), ("verifier_y", Some("rcpt_verifier_y_001".to_string()))] {
        engine.record_verification(&row.task_id, VerifyRequest {
            result_id: r.result_id, verifier_id: v.into(), outcome: "reproduced".into(), verifier_content_hash: r.content_hash.clone(), signature: None,
            workload_version: None, submission_nonce: None, verifier_receipt_id: rc, notes: None,
        }).await.unwrap();
    }
    (Arc::new(db), obj_id, row.task_id)
}
async fn start_scheduler_api(db: Arc<dyn ResearchDb>) -> String {
    let state = AppState { scheduler: ResearchScheduler::new(db.clone()).with_lease_secs(60), miners: MinerRegistry::new(), verification: VerificationEngine::new(db),
                           verifier_registry: None, beacon: BeaconService::stub() };
    let l = tokio::net::TcpListener::bind("127.0.0.1:0").await.unwrap();
    let url = format!("http://{}", l.local_addr().unwrap());
    tokio::spawn(async move { axum::serve(l, router(state)).await.unwrap(); });
    url
}
async fn post_json(url: &str, body: &Value) -> (u16, Value) {
    let r = reqwest::Client::new().post(url).json(body).send().await.unwrap();
    (r.status().as_u16(), r.json().await.unwrap_or(Value::Null))
}

// ═════════════════════════════════════ the v2 chain ═════════════════════════════════════════════════════════════════════
#[tokio::test(flavor = "multi_thread", worker_threads = 2)]
async fn four_real_nodes_on_a_fresh_qattice_v2_genesis_settle_signed_transfers_and_a_research_reward() {
    let _one = ONE_AT_A_TIME.lock().unwrap_or_else(|e| e.into_inner());
    let keys = std::env::temp_dir().join(format!("qattice-v2-live-keys-{}", std::process::id()));
    let _ = std::fs::remove_dir_all(&keys);
    std::fs::create_dir_all(&keys).unwrap();
    let (op, user, sink) = (new_wallet(&keys, "operator"), new_wallet(&keys, "user"), new_wallet(&keys, "sink"));
    let (lkp, laddr) = legacy_key();

    let tmpl = repo_root().join("tests/devnet/qattice-v2/genesis-4node-qattice-v2.json");
    let dir = std::env::temp_dir().join(format!("qattice-v2-live-genesis-{}", std::process::id()));
    std::fs::create_dir_all(&dir).unwrap();
    let genesis = render_genesis(&tmpl, &dir, vec![
        account("Operator (settlement)", &op.address, "5000000000", "user"),
        account("User", &user.address, "50000000", "user"),
        account("Legacy-key user", &laddr, "50000000", "user"),
        account("PoCD research treasury", TREASURY, "100000000000", "treasury"),
    ], Some(&op.address));
    println!("\n── four real nodes, chain {CHAIN_V2} (commitment_profile qattice-v2) ──");
    let net = start_net(&genesis, "v2");
    assert_eq!(status(net.alice())["chain_id"], CHAIN_V2);

    // V-01 / V-02: transfers signed locally by the real wallet CLI.
    println!("  V-01/V-02 local signing");
    let t0 = sign_transfer(&user, &sink.address, 1_000, 0, CHAIN_V2, "v2-t0", true);
    assert_eq!(t0["sig_scheme"], "MlDsa");
    expect_committed(&net, &t0, "V-01");
    assert_eq!(net.on_all(|p| balance(p, &sink.address), "V-01 balance"), 1_000);
    assert_eq!(net.on_all(|p| nonce(p, &user.address), "V-01 nonce"), 1);
    let t1 = sign_transfer(&user, &sink.address, 2_000, 1, CHAIN_V2, "v2-t1", false);
    assert!(t1["pq_public_key"].as_array().map_or(true, |a| a.is_empty()) || t1["pq_public_key"].is_null(), "the bound key is not carried again");
    expect_committed(&net, &t1, "V-02");
    assert_eq!(net.on_all(|p| balance(p, &sink.address), "V-02 balance"), 3_000);

    // API contract (PR #116): committed results keep their legacy shape; an unknown id is still a 404 with the legacy body.
    let done = api_get(net.alice(), "/api/tx/v2-t0").expect("a committed tx is readable");
    assert_eq!(done["success"], true, "{done}");
    assert!(done.get("code").is_none() && done.get("state").is_none(), "a committed result must not look like a refusal: {done}");
    let (code, body) = http_raw("GET", net.alice(), "/api/tx/never-submitted", None).map(|(c, b)| (c, b)).unwrap();
    assert_eq!((code, body.as_str()), (404, r#"{"error":"not found"}"#), "an unknown id keeps the legacy 404");

    // V-03..V-07: refusals; nothing about the sender may change anywhere.
    println!("  V-03..V-07 refusals");
    expect_not_applied(&net, &t1, &user.address, "V-03 exact replay of an executed tx", None);
    let mut moved = t1.clone(); moved["nonce"] = json!(2); moved["id"] = json!("v2-replayed-nonce");
    expect_not_applied(&net, &moved, &user.address, "V-04 same signature, new nonce and id", Some("signing_v2_authorization"));
    let mut edited = sign_transfer(&user, &sink.address, 10, 2, CHAIN_V2, "v2-edited", false);
    edited["body"]["Transfer"]["amount"] = json!(9_999_999u64);
    expect_not_applied(&net, &edited, &user.address, "V-05 body edited after signing", Some("signing_v2_authorization"));
    let other = sign_transfer(&user, &sink.address, 10, 2, "some-other-chain", "v2-other-chain", false);
    expect_not_applied(&net, &other, &user.address, "V-06 signature made for another chain id", Some("signing_v2_authorization"));
    let legacy = legacy_transfer(&lkp, &laddr, &sink.address, "legacy-on-v2", 0, CHAIN_V2);
    expect_not_applied(&net, &legacy, &laddr, "V-07 legacy-digest signature on a v2 chain", None);
    // After all that, a correct transfer at the same nonce still works: the refusals consumed nothing.
    let t2 = sign_transfer(&user, &sink.address, 500, 2, CHAIN_V2, "v2-t2", false);
    expect_committed(&net, &t2, "V-03..07 control");

    // V-08: prepare -> external signer -> submit, against the real nodes.
    println!("  V-08/V-09 prepare -> qcb-claim-signer -> submit");
    let (db, obj, task) = accepted_task().await;
    let api = start_scheduler_api(db).await;
    let op_nonce = net.on_all(|p| nonce(p, &op.address), "operator nonce");
    let (treasury0, sink0) = (net.on_all(|p| balance(p, TREASURY), "treasury"), net.on_all(|p| balance(p, &sink.address), "sink"));
    let (code, prepared) = post_json(&format!("{api}/scheduler/objectives/{obj}/settle/prepare"), &json!({
        "task_id": task, "reward_kind": "primary", "recipient": sink.address, "chain_id": CHAIN_V2, "operator_address": op.address,
        "operator_public_key_hex": op.public_key, "carry_key": true, "operator_nonce": op_nonce, "disbursed_uqcb": 0, "signing_profile": "qattice-v2" })).await;
    assert_eq!(code, 200, "{prepared}");
    let amount = prepared["amount_uqcb"].as_u64().expect("amount");
    let pf = keys.join("prepared.json");
    std::fs::write(&pf, serde_json::to_vec(&prepared).unwrap()).unwrap();
    // a wrong --expect-chain-id makes the signer refuse
    let bad = Command::new(env!("CARGO_BIN_EXE_qcb-claim-signer")).args(["--wallet", &op.file, "--prepared", pf.to_str().unwrap(), "--expect-chain-id", "some-other-chain"])
        .env("QCB_WALLET_PASSPHRASE", PASS).output().unwrap();
    assert!(!bad.status.success() && bad.stdout.is_empty(), "V-09: the signer must refuse a claim for a chain it was not told to expect");
    let good = Command::new(env!("CARGO_BIN_EXE_qcb-claim-signer")).args(["--wallet", &op.file, "--prepared", pf.to_str().unwrap(), "--expect-chain-id", CHAIN_V2])
        .env("QCB_WALLET_PASSPHRASE", PASS).output().unwrap();
    assert!(good.status.success(), "{}", String::from_utf8_lossy(&good.stderr));
    let signed: Value = serde_json::from_slice(&good.stdout).unwrap();
    let node_url = format!("http://127.0.0.1:{}", net.alice());
    let (code, resp) = post_json(&format!("{api}/scheduler/objectives/{obj}/settle/submit"),
        &json!({ "claim_id": signed["claim_id"], "chain_id": CHAIN_V2, "signed_tx": signed["signed_tx"], "node_url": node_url })).await;
    assert_eq!(code, 201, "V-08: {resp}");
    let claim_tx_id = signed["signed_tx"]["id"].as_str().unwrap().to_string();
    let r = wait_tx_result(net.alice(), &claim_tx_id, 90).unwrap_or_else(|| { net.dump_logs(); panic!("V-08: the claim was not executed") });
    assert!(r["success"].as_bool().unwrap_or(false), "V-08: the claim must succeed on the node: {r}");
    let h = r["height"].as_u64().unwrap();
    net.assert_converged(h, "V-08");
    for &p in &net.api {
        let b = api_get(p, &format!("/api/blocks/{h}")).unwrap_or(Value::Null);
        assert!(b["tx_ids"].as_array().map_or(false, |a| a.iter().any(|x| x == claim_tx_id.as_str())), "V-08: block {h} on :{p} does not list the claim: {b}");
    }
    assert_eq!(net.on_all(|p| balance(p, &sink.address), "V-08 recipient") , sink0 + amount as u128, "recipient credited exactly the claim amount");
    assert_eq!(net.on_all(|p| balance(p, TREASURY), "V-08 treasury"), treasury0 - amount as u128, "treasury debited exactly the claim amount");
    assert_eq!(net.on_all(|p| nonce(p, &op.address), "V-08 operator nonce"), op_nonce + 1);
    println!("    V-08: claim {claim_tx_id} settled in block {h}: {amount} uqcb treasury -> recipient; roots agree");

    // V-09: replay of the settled claim, at a node and through the scheduler.
    expect_not_applied(&net, &signed["signed_tx"], &op.address, "V-09 replay of the settled claim at a node", None);
    assert_eq!(net.on_all(|p| balance(p, TREASURY), "V-09 treasury"), treasury0 - amount as u128, "no second payout");
    let (code, resp) = post_json(&format!("{api}/scheduler/objectives/{obj}/settle/submit"),
        &json!({ "claim_id": signed["claim_id"], "chain_id": CHAIN_V2, "signed_tx": signed["signed_tx"], "node_url": node_url })).await;
    assert_eq!(code, 409, "V-09: the scheduler must refuse to submit a settled claim again: {resp}");
    net.assert_converged(0, "final");
    println!("  ✓ all v2 checks passed; final height {}", height(net.alice()));
    drop(net);
    let _ = std::fs::remove_dir_all(&keys);
    let _ = std::fs::remove_dir_all(&dir);
}

// ═════════════════════════════════════ the legacy chain ═════════════════════════════════════════════════════════════════
#[tokio::test(flavor = "multi_thread", worker_threads = 2)]
async fn a_legacy_chain_with_the_same_binary_accepts_legacy_signatures_and_refuses_v2() {
    let _one = ONE_AT_A_TIME.lock().unwrap_or_else(|e| e.into_inner());
    let keys = std::env::temp_dir().join(format!("qattice-v2-live-legacy-keys-{}", std::process::id()));
    let _ = std::fs::remove_dir_all(&keys);
    std::fs::create_dir_all(&keys).unwrap();
    let v2user = new_wallet(&keys, "v2user");
    let (lkp, laddr) = legacy_key();
    // The EXISTING supported devnet genesis, unchanged on disk; only a temp copy gets the two test accounts.
    let tmpl = repo_root().join("tests/devnet/genesis-4node-mldsa.json");
    let dir = std::env::temp_dir().join(format!("qattice-v2-live-legacy-genesis-{}", std::process::id()));
    std::fs::create_dir_all(&dir).unwrap();
    let genesis = render_genesis(&tmpl, &dir, vec![
        account("Legacy-key user", &laddr, "50000000", "user"),
        account("v2-wallet user", &v2user.address, "50000000", "user"),
    ], None);
    println!("\n── four real nodes, LEGACY chain {CHAIN_LEGACY} (no commitment_profile) ──");
    let net = start_net(&genesis, "legacy");
    assert_eq!(status(net.alice())["chain_id"], CHAIN_LEGACY);
    let ok = legacy_transfer(&lkp, &laddr, "qcb1bob", "legacy-ok", 0, CHAIN_LEGACY);
    expect_committed(&net, &ok, "L-01 legacy-signed transfer on a legacy chain");
    assert_eq!(net.on_all(|p| nonce(p, &laddr), "L-01 nonce"), 1);
    let v2 = sign_transfer(&v2user, "qcb1bob", 1_000, 0, CHAIN_LEGACY, "v2-on-legacy", true);
    expect_not_applied(&net, &v2, &v2user.address, "L-02 v2-signed transaction on a legacy chain", None);
    net.assert_converged(0, "final");
    println!("  ✓ legacy chain: legacy accepted, v2 refused; roots agree");
    drop(net);
    let _ = std::fs::remove_dir_all(&keys);
    let _ = std::fs::remove_dir_all(&dir);
}
